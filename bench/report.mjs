#!/usr/bin/env node
// Summarizes bench/results/raw/*.jsonl into results/summary.md and the README
// chart results/chart.svg. Medians are per task and setup across reps.
//
//   node bench/report.mjs [results/raw/file.jsonl ...]
import fs from "node:fs";
import path from "node:path";
import { benchDir } from "./lib/env.mjs";
import { TASKS } from "./lib/tasks.mjs";

const rawDir = path.join(benchDir, "results", "raw");
const files = process.argv.slice(2).length
  ? process.argv.slice(2)
  : fs.readdirSync(rawDir).filter((f) => f.endsWith(".jsonl")).map((f) => path.join(rawDir, f));
const records = files.flatMap((f) => fs.readFileSync(f, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l)));
if (!records.length) throw new Error("No results yet. Run node bench/run.mjs first.");

const SETUPS = [
  { id: "glovebox", label: "glovebox" },
  { id: "cu", label: "Anthropic computer use" },
  { id: "ocu", label: "open-computer-use" },
];
const tasks = TASKS.map((t) => t.id).filter((id) => records.some((r) => r.task === id));

function median(values) {
  const v = values.filter((x) => x != null).sort((a, b) => a - b);
  if (!v.length) return null;
  const mid = Math.floor(v.length / 2);
  return v.length % 2 ? v[mid] : (v[mid - 1] + v[mid]) / 2;
}

function cell(task, setup) {
  const rs = records.filter((r) => r.task === task && r.setup === setup);
  if (!rs.length) return null;
  const sum = (f) => rs.reduce((n, r) => n + (f(r) ?? 0), 0);
  return {
    runs: rs.length,
    passed: rs.filter((r) => r.success).length,
    roundTrips: median(rs.map((r) => r.roundTrips)),
    cost: median(rs.map((r) => r.costUsd)),
    images: median(rs.map((r) => r.images)),
    wallS: median(rs.map((r) => r.wallMs / 1000)),
    input: sum((r) => r.usage?.input),
    cacheWrite: sum((r) => r.usage?.cacheWrite),
    cacheRead: sum((r) => r.usage?.cacheRead),
    output: sum((r) => r.usage?.output),
    perSegment: rs.map((r) => r.roundTripsPerSegment?.join("/")).filter(Boolean),
    reads: rs.map((r) => r.reads).filter(Boolean),
  };
}

const fmt = {
  n: (v) => (v == null ? "—" : Number.isInteger(v) ? String(v) : v.toFixed(1)),
  usd: (v) => (v == null ? "—" : `$${v < 0.1 ? v.toFixed(3) : v.toFixed(2)}`),
  k: (v) => (v >= 1000 ? `${(v / 1000).toFixed(1)}k` : String(v)),
};

// ---- summary.md -------------------------------------------------------------
const models = [...new Set(records.map((r) => `${r.model} (effort ${r.effort})`))].join(", ");
const dates = records.map((r) => r.date.slice(0, 10)).sort();
const lines = [
  "# Benchmark results",
  "",
  `${records.length} runs, ${dates[0]} to ${dates.at(-1)}, ${models}. Medians per task across runs; costs at list price.`,
  "Generated by `node bench/report.mjs` from `results/raw/`.",
  "",
  "| Task | Setup | Passed | Round trips | Cost | Images | Wall (s) |",
  "|---|---|---|---|---|---|---|",
];
for (const task of tasks) {
  for (const s of SETUPS) {
    const c = cell(task, s.id);
    if (!c) continue;
    lines.push(`| ${task} | ${s.label} | ${c.passed}/${c.runs} | ${fmt.n(c.roundTrips)} | ${fmt.usd(c.cost)} | ${fmt.n(c.images)} | ${fmt.n(c.wallS)} |`);
  }
}
lines.push("", "## Totals by setup", "", "| Setup | Passed | Round trips | Uncached in | Cache write | Cache read | Output | Images | Cost |", "|---|---|---|---|---|---|---|---|---|");
for (const s of SETUPS) {
  const rs = records.filter((r) => r.setup === s.id);
  if (!rs.length) continue;
  const sum = (f) => rs.reduce((n, r) => n + (f(r) ?? 0), 0);
  lines.push(
    `| ${s.label} | ${rs.filter((r) => r.success).length}/${rs.length} | ${sum((r) => r.roundTrips)} | ${fmt.k(sum((r) => r.usage?.input))} | ${fmt.k(sum((r) => r.usage?.cacheWrite))} | ${fmt.k(sum((r) => r.usage?.cacheRead))} | ${fmt.k(sum((r) => r.usage?.output))} | ${sum((r) => r.images)} | ${fmt.usd(sum((r) => r.costUsd))} |`,
  );
}
const repeat = SETUPS.map((s) => [s, cell("form-repeat", s.id)]).filter(([, c]) => c);
if (repeat.length) {
  lines.push("", "## Replay baseline (form-repeat)", "", "Round trips for the first, second, and third record in one conversation.", "");
  for (const [s, c] of repeat) lines.push(`- ${s.label}: ${c.perSegment.join(", ") || "—"}`);
}
const reads = records.filter((r) => r.reads);
if (reads.length) {
  const sum = (k) => reads.reduce((n, r) => n + r.reads[k], 0);
  const textRuns = records.filter((r) => r.setup === "glovebox" && r.kind === "text");
  lines.push(
    "",
    "## glovebox reads",
    "",
    `Across ${reads.length} glovebox runs: ${sum("fullReads")} full trees, ${sum("diffReads")} diffs, ${sum("noChangeReads")} "no change" results.`,
    `Full reprints of a window already printed: ${sum("reprints")}. "No change" followed by another read before acting: ${sum("noChangeThenRead")}.`,
    `Screenshots on tasks the tree can solve: ${textRuns.reduce((n, r) => n + (r.screenshotsOnTextTask ?? 0), 0)} across ${textRuns.length} runs.`,
  );
}
const failures = records.filter((r) => !r.success);
if (failures.length) {
  lines.push("", "## Failed runs", "");
  for (const r of failures) lines.push(`- ${r.task} × ${r.setup} (rep ${r.rep + 1}): ${r.error ?? r.detail}`);
}
fs.writeFileSync(path.join(benchDir, "results", "summary.md"), `${lines.join("\n")}\n`);

// ---- chart.svg --------------------------------------------------------------
// Two panels with their own axes (never a dual axis): median round trips and
// median cost. Horizontal grouped bars, one group per task, a value label on
// every bar so identity and value never depend on color alone.
const W = 760;
const LEFT = 132;
const RIGHT = 56;
const BAR = 9;
const GAP = 2;
const GROUP = SETUPS.length * (BAR + GAP) + 10;

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
}

// A round tick step giving at most five intervals, and the axis max it implies.
function niceScale(v) {
  const rough = (v || 1) / 5;
  const p = 10 ** Math.floor(Math.log10(rough));
  const step = [1, 2, 2.5, 5, 10].map((m) => m * p).find((m) => m >= rough);
  return { step, max: Math.ceil(v / step) * step || step };
}

function panel(y0, title, key, format) {
  const values = tasks.flatMap((t) => SETUPS.map((s) => cell(t, s.id)?.[key] ?? 0));
  const { step, max } = niceScale(Math.max(...values));
  const plotW = W - LEFT - RIGHT;
  const x = (v) => LEFT + (v / max) * plotW;
  const top = y0 + 28;
  const height = tasks.length * GROUP;
  const out = [`<text class="title" x="${LEFT}" y="${y0 + 14}">${esc(title)}</text>`];
  // Enough decimals for the step: 0.05 needs 2, 2.5 needs 1.
  const magnitude = Math.floor(Math.log10(step) + 1e-9);
  const fractional = Math.abs(step / 10 ** magnitude - Math.round(step / 10 ** magnitude)) > 1e-9;
  const decimals = Math.max(0, -magnitude + (fractional ? 1 : 0));
  for (let v = 0; v <= max + step / 2; v += step) {
    out.push(`<line class="grid" x1="${x(v)}" x2="${x(v)}" y1="${top}" y2="${top + height}"/>`);
    out.push(`<text class="tick" x="${x(v)}" y="${top + height + 14}" text-anchor="middle">${esc(format(v, decimals))}</text>`);
  }
  tasks.forEach((task, ti) => {
    const gy = top + ti * GROUP;
    out.push(`<text class="label" x="${LEFT - 10}" y="${gy + (SETUPS.length * (BAR + GAP)) / 2 + 3}" text-anchor="end">${esc(task)}</text>`);
    SETUPS.forEach((s, si) => {
      const c = cell(task, s.id);
      if (!c) return;
      const v = c[key] ?? 0;
      const by = gy + si * (BAR + GAP);
      const w = Math.max(1, x(v) - LEFT);
      // Square at the baseline, 4px rounded at the data end.
      const r = Math.min(4, w, BAR / 2);
      const d = `M${LEFT},${by} h${w - r} a${r},${r} 0 0 1 ${r},${r} v${BAR - 2 * r} a${r},${r} 0 0 1 -${r},${r} h-${w - r} z`;
      out.push(`<path class="s${si}" d="${d}"><title>${esc(`${task} · ${s.label}: ${format(v)} (${c.passed}/${c.runs} passed)`)}</title></path>`);
      // Medians include failed runs, so say when a cell had any.
      const passed = c.passed < c.runs ? ` · ${c.passed}/${c.runs} passed` : "";
      out.push(`<text class="value" x="${LEFT + w + 4}" y="${by + BAR - 1}">${esc(format(v) + passed)}</text>`);
    });
  });
  out.push(`<line class="axis" x1="${LEFT}" x2="${LEFT}" y1="${top}" y2="${top + height}"/>`);
  return { svg: out.join("\n"), bottom: top + height + 22 };
}

const legend = SETUPS.map((s, i) => {
  const lx = LEFT + i * 190;
  return `<rect class="s${i}" x="${lx}" y="12" width="12" height="12" rx="3"/><text class="label" x="${lx + 18}" y="22">${esc(s.label)}</text>`;
}).join("\n");
// format(value, tickDecimals): tickDecimals is set only for axis ticks.
const p1 = panel(40, "Median model round trips per task", "roundTrips", (v, d) => (d == null ? fmt.n(v) : v.toFixed(d)));
const p2 = panel(p1.bottom + 16, "Median cost per task (USD, list price)", "cost", (v, d) => (d == null ? fmt.usd(v) : `$${v.toFixed(d)}`));
const H = p2.bottom + 24;
const note = `${records.length} runs · ${esc(models)} · medians per task, failed runs included`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-labelledby="t d">
<title id="t">glovebox benchmark: round trips and cost per task</title>
<desc id="d">Grouped bars comparing glovebox, Anthropic computer use, and open-computer-use on ${tasks.length} macOS tasks. Full numbers are in bench/results/summary.md.</desc>
<style>
  svg { --surface: #fcfcfb; --ink: #0b0b0b; --ink-2: #52514e; --grid: #e4e3df; --s0: #2a78d6; --s1: #eb6834; --s2: #1baf7a; font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif; }
  @media (prefers-color-scheme: dark) { svg { --surface: #1a1a19; --ink: #f0efec; --ink-2: #c3c2b7; --grid: #34332f; --s0: #3987e5; --s1: #d95926; --s2: #199e70; } }
  .bg { fill: var(--surface); }
  .title { fill: var(--ink); font-size: 13px; font-weight: 600; }
  .label { fill: var(--ink); font-size: 12px; }
  .value, .tick, .note { fill: var(--ink-2); font-size: 10.5px; }
  .grid { stroke: var(--grid); stroke-width: 1; }
  .axis { stroke: var(--ink-2); stroke-width: 1; }
  .s0 { fill: var(--s0); } .s1 { fill: var(--s1); } .s2 { fill: var(--s2); }
</style>
<rect class="bg" width="${W}" height="${H}" rx="8"/>
${legend}
${p1.svg}
${p2.svg}
<text class="note" x="${LEFT}" y="${H - 10}">${note}</text>
</svg>
`;
fs.writeFileSync(path.join(benchDir, "results", "chart.svg"), svg);
console.log(`Wrote results/summary.md and results/chart.svg from ${records.length} runs.`);
